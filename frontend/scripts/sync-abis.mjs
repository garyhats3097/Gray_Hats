// Copies contract ABIs from Foundry's build output into src/config/abis.ts.
// Run after changing contracts:  cd contracts && forge build && cd ../frontend && npm run sync-abis
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../contracts/out");
const contracts = ["CoreVault", "ModuleRegistry", "PerpsModule", "LendingModule", "MockOracle", "MockERC20"];

let ts = "// AUTO-GENERATED by scripts/sync-abis.mjs — do not edit by hand.\n\n";
for (const name of contracts) {
  const { abi } = JSON.parse(readFileSync(`${out}/${name}.sol/${name}.json`, "utf8"));
  ts += `export const ${name[0].toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(resolve(here, "../src/config/abis.ts"), ts);
console.log(`Wrote ${contracts.length} ABIs to src/config/abis.ts`);
